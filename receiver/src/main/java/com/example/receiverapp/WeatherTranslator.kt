            1246 -> "ฝนตกหนักมากเป็นช่วงๆ"
            1249 -> "ฝนปนหิมะตกเป็นช่วงๆ"
            1252 -> "ฝนปนหิมะตกหนักเป็นช่วงๆ"
            1255 -> "หิมะตกเป็นช่วงๆ"
