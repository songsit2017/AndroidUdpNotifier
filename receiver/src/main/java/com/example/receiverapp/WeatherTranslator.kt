            1261 -> "ลูกเห็บตกเป็นช่วงๆ"
            1264 -> "ลูกเห็บตกหนักเป็นช่วงๆ"
            1273 -> "ฝนฟ้าคะนองเล็กน้อย"
            1276 -> "ฝนฟ้าคะนองปานกลาง"
            1279 -> "พายุหิมะฟ้าคะนองเล็กน้อย"
            1282 -> "พายุหิมะฟ้าคะนองหนัก"
            else -> translateText(originalText)
        }
    }

    private fun translateText(text: String): String {
        val lower = text.lowercase().trim()
        return when {
            "patchy rain" in lower -> "ฝนโปรยปราย"
            "sunny" in lower -> "แดดจัด"
            "clear" in lower -> "ท้องฟ้าแจ่มใส"
            "partly cloudy" in lower -> "มีเมฆบางส่วน"
            "cloudy" in lower -> "มีเมฆมาก"
            "overcast" in lower -> "เมฆครึ้ม"
            "light rain" in lower -> "ฝนตกเล็กน้อย"
            "moderate rain" in lower -> "ฝนตกปานกลาง"
            "heavy rain" in lower -> "ฝนตกหนัก"
            "thunder" in lower -> "ฝนฟ้าคะนอง"
            "shower" in lower -> "ฝนซู่"
            "drizzle" in lower -> "ฝนปรอยๆ"
            "mist" in lower || "fog" in lower -> "มีหมอก"
            text.isNotBlank() -> text
            else -> "สภาพอากาศปกติ"
        }
    }
}
