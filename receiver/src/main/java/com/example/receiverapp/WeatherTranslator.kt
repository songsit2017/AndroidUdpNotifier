            1066 -> "หิมะตกบางแห่ง"
            1069 -> "ฝนปนหิมะ"
            1072 -> "ฝนเยือกแข็ง"
            1087 -> "อาจมีฝนฟ้าคะนอง"
            1114 -> "หิมะตก"
            1117 -> "พายุหิมะ"
            1135 -> "มีหมอกลง"
            1147 -> "หมอกเยือกแข็ง"
            1150 -> "ฝนปรอยๆ เป็นหย่อมๆ"
            1153 -> "ฝนตกปรอยๆ"
            1168 -> "ฝนปรอยเยือกแข็ง"
            1171 -> "ฝนปรอยเยือกแข็งหนัก"
            1180 -> "ฝนตกเล็กน้อยบางแห่ง"
            1183 -> "ฝนตกเล็กน้อย"
