            1201 -> "ฝนเยือกแข็งปานกลาง"
            1204 -> "ฝนปนหิมะเล็กน้อย"
            1207 -> "ฝนปนหิมะปานกลาง/หนัก"
            1210 -> "หิมะตกเล็กน้อยบางแห่ง"
            1213 -> "หิมะตกเล็กน้อย"
            1216 -> "หิมะตกปานกลางบางแห่ง"
            1219 -> "หิมะตกปานกลาง"
